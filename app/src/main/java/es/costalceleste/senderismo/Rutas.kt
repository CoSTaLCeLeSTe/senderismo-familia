package es.costalceleste.senderismo

import kotlin.math.roundToInt

enum class Base(val label: String) {
    SEVILLA("Sevilla"),
    PUERTO("El Puerto"),
}

enum class Provincia(val label: String) {
    SEVILLA("Sevilla"),
    CADIZ("Cádiz"),
    HUELVA("Huelva"),
}

enum class Modo(val label: String) {
    MOCHILA("Portabebés"),
    CARRITO("Carrito"),
    MIXTA("Carrito o portabebés"),
}

enum class Semaforo(val label: String, val color: Long) {
    VERDE("Verde · paseo", 0xFF3E9B5F),
    AMARILLO("Amarillo · cargar al peque un buen rato", 0xFFE0A526),
    ROJO("Rojo · todavía no", 0xFFC8483B),
}

data class Ruta(
    val id: String,
    val nombre: String,
    val zona: String,
    val provincia: Provincia,
    val bases: List<Base>,
    val distanciaOficial: String,
    val recorridoPropuesto: String,
    /** Kilómetros del recorrido propuesto para la familia. */
    val km: Double,
    val modo: Modo,
    val semaforo: Semaforo,
    val porque: String,
    val avisos: String,
    /** Coordenadas aproximadas de la zona, para la previsión del tiempo. */
    val lat: Double,
    val lon: Double,
    /** Texto que se busca en Google Maps para llegar al inicio. */
    val busquedaMapa: String,
    /** Minutos de coche aproximados desde cada base. Se ajustan en el plan. */
    val minutosCoche: Map<Base, Int>,
    val fuente: String,
) {
    /** Duración a ritmo familiar: más lento que el oficial y con un 25 % de paradas. */
    fun duracionMin(): Int {
        val ritmoKmH = if (modo == Modo.CARRITO) 3.0 else 2.5
        return (km / ritmoKmH * 60 * 1.25).roundToInt()
    }
}

